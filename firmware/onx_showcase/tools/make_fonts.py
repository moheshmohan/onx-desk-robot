#!/usr/bin/env python3
"""Rasterise Montserrat (SIL Open Font License) into 8-bit alpha glyph tables.

Usage: make_fonts.py <Montserrat-Medium.ttf> <Montserrat-Bold.ttf> > ../fonts.h
Character code 127 is used for the degree sign.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

MEDIUM, BOLD = sys.argv[1], sys.argv[2]
ASCII = [chr(c) for c in range(32, 127)]
FONTS = [  # name, file, pixel size, characters
    ("FS", MEDIUM, 14, ASCII + ["\x7f"]),
    ("FM", MEDIUM, 20, ASCII + ["\x7f"]),
    ("FL", BOLD, 30, ASCII + ["\x7f"]),
    ("FX", BOLD, 58, list(" 0123456789:.-%") + ["\x7f"]),
]

out = ["// Generated by tools/make_fonts.py. Do not edit.",
       "// Glyphs are Montserrat, (c) The Montserrat Project Authors, SIL Open Font License 1.1.",
       "#pragma once", ""]
for name, path, size, chars in FONTS:
    font = ImageFont.truetype(path, size)
    pad = size
    data, glyphs = bytearray(), {}
    for ch in chars:
        real = "°" if ch == "\x7f" else ch
        img = Image.new("L", (size * 3, size * 3), 0)
        ImageDraw.Draw(img).text((pad, pad * 2), real, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        adv = int(round(font.getlength(real) * 16))
        if box is None:
            glyphs[ord(ch)] = (len(data), 0, 0, 0, 0, adv)
            continue
        crop = img.crop(box)
        glyphs[ord(ch)] = (len(data), crop.width, crop.height, box[0] - pad, box[1] - pad * 2, adv)
        data += crop.tobytes()
    capbox = font.getbbox("0", anchor="ls")
    cap = -capbox[1]
    out.append(f"static const uint8_t {name}_bmp[] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const gfx::Glyph {name}_gl[] = {{")
    for code in range(32, 128):
        off, w, h, xo, yo, adv = glyphs.get(code, (0, 0, 0, 0, 0, 0))
        out.append(f"  {{{off},{w},{h},{xo},{yo},{adv}}},")
    out.append("};")
    out.append(f"static const gfx::Font {name} = {{{name}_bmp, {name}_gl, 32, 127, {cap}}};")
    out.append("")
    print(f"{name}: {size}px, {len(chars)} glyphs, {len(data)} bytes, cap {cap}", file=sys.stderr)
print("\n".join(out))
